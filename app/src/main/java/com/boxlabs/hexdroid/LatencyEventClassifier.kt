package com.boxlabs.hexdroid

/** Stable diagnostic labels; deliberately contains no network, channel, nick, or message data. */
internal fun latencyEventKind(ev: IrcEvent): String = when (ev) {
    is IrcEvent.ChatMessage -> if (ev.isHistory) "ChatHistory" else "ChatLive"
    is IrcEvent.Names -> "Names"
    is IrcEvent.NamesEnd -> "NamesEnd"
    is IrcEvent.Joined -> "Joined"
    is IrcEvent.Parted -> "Parted"
    is IrcEvent.Kicked -> "Kicked"
    is IrcEvent.Quit -> "Quit"
    is IrcEvent.NickChanged -> "NickChanged"
    is IrcEvent.ChannelModeChanges -> "ChannelModeChanges"
    is IrcEvent.ChannelUserMode -> "ChannelUserMode"
    is IrcEvent.ChannelModeChanged -> "ChannelModeChanged"
    is IrcEvent.ChannelModeLine -> "ChannelModeLine"
    is IrcEvent.WhoxReply -> "WhoxReply"
    is IrcEvent.Notice -> "Notice"
    is IrcEvent.Status -> "Status"
    is IrcEvent.ServerText -> "ServerText"
    is IrcEvent.ServerLine -> "ServerLine"
    is IrcEvent.RawLine -> "RawLine"
    is IrcEvent.BanListItem -> "BanListItem"
    is IrcEvent.BanListEnd -> "BanListEnd"
    is IrcEvent.QuietListItem -> "QuietListItem"
    is IrcEvent.QuietListEnd -> "QuietListEnd"
    is IrcEvent.ExceptListItem -> "ExceptListItem"
    is IrcEvent.ExceptListEnd -> "ExceptListEnd"
    is IrcEvent.InvexListItem -> "InvexListItem"
    is IrcEvent.InvexListEnd -> "InvexListEnd"
    is IrcEvent.ChannelListItem -> "ChannelListItem"
    is IrcEvent.ChannelListEnd -> "ChannelListEnd"
    is IrcEvent.TypingStatus -> "TypingStatus"
    is IrcEvent.AwayChanged -> "AwayChanged"
    is IrcEvent.AccountChanged -> "AccountChanged"
    is IrcEvent.Setname -> "Setname"
    is IrcEvent.MetadataChanged -> "MetadataChanged"
    is IrcEvent.MessageReaction -> "MessageReaction"
    is IrcEvent.ReadReceipt -> "ReadReceipt"
    is IrcEvent.CtcpReply -> "CtcpReply"
    is IrcEvent.CtcpRequest -> "CtcpRequest"
    is IrcEvent.CtcpExchange -> "CtcpExchange"
    is IrcEvent.OwnUserModeChanged -> "OwnUserModeChanged"
    is IrcEvent.DccOfferEvent -> "DccOffer"
    is IrcEvent.DccChatOfferEvent -> "DccChatOffer"
    is IrcEvent.DccResumeRequest -> "DccResume"
    is IrcEvent.DccAcceptResponse -> "DccAccept"
    is IrcEvent.WebPushFailed -> "WebPushFailed"
    else -> "Other"
}
